-- V16: continuous assurance foundation.
create table if not exists public.assurance_controls(
 id uuid primary key default gen_random_uuid(),
 control_key text not null,
 version integer not null check(version>0),
 name text not null,
 category text not null check(category in ('control','action','automation','security','operations','system')),
 severity text not null default 'warning' check(severity in ('info','warning','high','critical')),
 weight integer not null default 10 check(weight between 1 and 100),
 freshness_minutes integer not null default 60 check(freshness_minutes between 5 and 10080),
 enabled boolean not null default true,
 check_kind text not null check(check_kind in ('sql_invariant','freshness','queue_health','governance')),
 definition jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(control_key,version)
);
alter table public.assurance_controls enable row level security;
revoke all on public.assurance_controls from public,anon,authenticated;
grant select,insert,update on public.assurance_controls to service_role;

create table if not exists public.assurance_runs(
 id uuid primary key default gen_random_uuid(),
 run_key text not null unique,
 status text not null default 'running' check(status in ('running','completed','failed')),
 started_at timestamptz not null default now(),
 completed_at timestamptz,
 controls_checked integer not null default 0,
 controls_passed integer not null default 0,
 controls_failed integer not null default 0,
 metadata jsonb not null default '{}'::jsonb
);
alter table public.assurance_runs enable row level security;
revoke all on public.assurance_runs from public,anon,authenticated;
grant select,insert,update on public.assurance_runs to service_role;

create table if not exists public.assurance_evidence(
 id uuid primary key default gen_random_uuid(),
 evidence_key text not null unique,
 run_id uuid not null references public.assurance_runs(id) on delete restrict,
 control_id uuid not null references public.assurance_controls(id) on delete restrict,
 status text not null check(status in ('pass','fail','error')),
 subject_key text not null default 'global',
 evidence jsonb not null default '{}'::jsonb,
 evidence_hash text not null,
 source_observed_at timestamptz,
 captured_at timestamptz not null default now()
);
create index if not exists assurance_evidence_control_idx on public.assurance_evidence(control_id,captured_at desc);
create index if not exists assurance_evidence_run_idx on public.assurance_evidence(run_id,status);
alter table public.assurance_evidence enable row level security;
revoke all on public.assurance_evidence from public,anon,authenticated;
grant select,insert on public.assurance_evidence to service_role;

create table if not exists public.assurance_findings(
 id uuid primary key default gen_random_uuid(),
 finding_key text not null unique,
 control_id uuid not null references public.assurance_controls(id) on delete restrict,
 subject_key text not null default 'global',
 status text not null default 'open' check(status in ('open','acknowledged','resolved','accepted_risk')),
 severity text not null check(severity in ('info','warning','high','critical')),
 title text not null,
 description text not null,
 occurrence_count integer not null default 1 check(occurrence_count>0),
 first_detected_at timestamptz not null default now(),
 incident_started_at timestamptz not null default now(),
 last_detected_at timestamptz not null default now(),
 last_evidence_id uuid references public.assurance_evidence(id) on delete set null,
 acknowledged_at timestamptz,
 acknowledged_by uuid references auth.users(id) on delete set null,
 resolved_at timestamptz,
 resolved_by uuid references auth.users(id) on delete set null,
 accepted_risk_at timestamptz,
 accepted_risk_by uuid references auth.users(id) on delete set null,
 accepted_risk_reason text,
 accepted_risk_expires_at timestamptz,
 updated_at timestamptz not null default now()
);
create index if not exists assurance_findings_queue_idx on public.assurance_findings(status,severity,last_detected_at desc);
create index if not exists assurance_findings_control_idx on public.assurance_findings(control_id,status);
alter table public.assurance_findings enable row level security;
revoke all on public.assurance_findings from public,anon,authenticated;
grant select,insert,update on public.assurance_findings to service_role;

create table if not exists public.assurance_events(
 id bigint generated by default as identity primary key,
 event_key text not null unique,
 finding_id uuid references public.assurance_findings(id) on delete restrict,
 run_id uuid references public.assurance_runs(id) on delete restrict,
 event_type text not null check(event_type in ('detected','redetected','acknowledged','resolved','reopened','risk_accepted','risk_expired','run_completed','run_failed')),
 actor_id uuid references auth.users(id) on delete set null,
 metadata jsonb not null default '{}'::jsonb,
 occurred_at timestamptz not null default now()
);
create index if not exists assurance_events_finding_idx on public.assurance_events(finding_id,occurred_at desc);
alter table public.assurance_events enable row level security;
revoke all on public.assurance_events from public,anon,authenticated;
grant select,insert on public.assurance_events to service_role;

comment on table public.assurance_evidence is 'Append-only V16 evidence snapshots proving control outcomes without mutating commerce state.';
comment on table public.assurance_findings is 'Deduplicated V16 assurance findings linked to failed controls.';
