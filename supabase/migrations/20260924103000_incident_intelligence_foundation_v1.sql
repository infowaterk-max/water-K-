create or replace function private.audit_platform_incident_state_v1()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_actor_kind text;
  v_actor_user uuid;
  v_details jsonb;
begin
  if tg_op='INSERT' then
    v_actor_kind:=private.platform_incident_actor_kind_v1(new.reporter_role);
    v_actor_user:=new.reporter_user_id;
    v_details:=jsonb_build_object(
      'source',new.source,'status',new.status,'ownership',new.ownership,'severity',new.severity,
      'routePath',new.route_path,'surfaceKey',new.surface_key,'componentKey',new.component_key
    );
    insert into public.platform_incident_events(incident_id,event_type,actor_kind,actor_user_id,correlation_id,details)
    values(new.id,'incident.created',v_actor_kind,v_actor_user,new.correlation_id,v_details);
    return new;
  end if;
  v_actor_kind:=coalesce(nullif(current_setting('app.incident_actor_kind',true),''),'system');
  begin v_actor_user:=nullif(current_setting('app.incident_actor_user_id',true),'')::uuid; exception when others then v_actor_user:=null; end;
  v_details:=jsonb_build_object(
    'oldStatus',old.status,'newStatus',new.status,
    'oldOwnership',old.ownership,'newOwnership',new.ownership,
    'oldSeverity',old.severity,'newSeverity',new.severity,
    'oldKnownFailureId',old.known_failure_id,'newKnownFailureId',new.known_failure_id,
    'ownershipReasonCode',new.ownership_reason_code
  );
  insert into public.platform_incident_events(incident_id,event_type,actor_kind,actor_user_id,correlation_id,details)
  values(new.id,'incident.updated',case when v_actor_kind in('anonymous','customer','merchant','platform','system','ai') then v_actor_kind else 'system' end,v_actor_user,new.correlation_id,v_details);
  return new;
end;
$$;
revoke all on function private.audit_platform_incident_state_v1() from public,anon,authenticated;
drop trigger if exists audit_platform_incident_state_trigger on public.platform_incidents;
create trigger audit_platform_incident_state_trigger after insert or update on public.platform_incidents
for each row execute function private.audit_platform_incident_state_v1();

