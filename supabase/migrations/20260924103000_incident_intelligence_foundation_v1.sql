  values(new.incident_id,v_type,case when v_kind in('anonymous','customer','merchant','platform','system','ai') then v_kind else 'system' end,v_user,
    private.incident_redact_json_v1(jsonb_build_object(
      'recordId',new.id,
      'status',case when tg_table_name='platform_repair_requests' then new.status else new.status end,
      'operation',tg_op
    ))
  );
  return new;
end;
$$;
