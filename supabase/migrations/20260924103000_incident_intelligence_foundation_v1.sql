create or replace function public.create_platform_incident_v1(
  p_instance_id uuid,
  p_support_ticket_id uuid,
  p_source text,
  p_reporter_user_id uuid,
  p_reporter_role text,
  p_title text,
  p_description text,
  p_category text,
  p_severity text,
  p_correlation_id text,
  p_route_path text,
  p_surface_key text,
  p_component_key text,
  p_app_version text,
  p_environment text,
  p_context jsonb default '{}'::jsonb,
  p_evidence jsonb default '{}'::jsonb
) returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_id uuid;
  v_number text;
  v_try integer;
begin
  if p_source not in('customer','merchant','system','observability') then raise exception 'INCIDENT_SOURCE_INVALID'; end if;
  if p_reporter_role not in('anonymous','customer','merchant_owner','merchant_admin','merchant_staff','platform','system','ai') then raise exception 'INCIDENT_REPORTER_ROLE_INVALID'; end if;
  if p_instance_id is not null and not exists(select 1 from public.webshop_instances where id=p_instance_id) then raise exception 'INCIDENT_INSTANCE_NOT_FOUND'; end if;
  if p_support_ticket_id is not null and not exists(
    select 1 from public.support_tickets t
    where t.id=p_support_ticket_id and (p_instance_id is null or t.instance_id=p_instance_id)
  ) then raise exception 'INCIDENT_SUPPORT_TICKET_SCOPE_MISMATCH'; end if;
  if p_source='customer' and p_support_ticket_id is null then raise exception 'INCIDENT_CUSTOMER_SUPPORT_TICKET_REQUIRED'; end if;
  if p_source='merchant' then
    if p_instance_id is null or p_reporter_user_id is null then raise exception 'INCIDENT_MERCHANT_CONTEXT_REQUIRED'; end if;
    if not exists(select 1 from public.webshop_instance_members m where m.instance_id=p_instance_id and m.user_id=p_reporter_user_id) then
      raise exception 'INCIDENT_MERCHANT_MEMBERSHIP_REQUIRED';
    end if;
  end if;
  if char_length(trim(coalesce(p_title,'')))<3 or char_length(trim(coalesce(p_title,'')))>180 then raise exception 'INCIDENT_TITLE_INVALID'; end if;
  if char_length(trim(coalesce(p_description,'')))<10 or char_length(trim(coalesce(p_description,'')))>8000 then raise exception 'INCIDENT_DESCRIPTION_INVALID'; end if;
  if p_category not in('ui','content','catalog','commerce','payment','shipping','account','integration','performance','security','data','other') then raise exception 'INCIDENT_CATEGORY_INVALID'; end if;
  if p_severity not in('low','normal','high','critical') then raise exception 'INCIDENT_SEVERITY_INVALID'; end if;

  for v_try in 1..5 loop
    v_number:='INC-'||to_char(now(),'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,8));
    begin
      insert into public.platform_incidents(
        incident_number,instance_id,support_ticket_id,source,reporter_user_id,reporter_role,
        title,description,category,severity,correlation_id,route_path,surface_key,component_key,
        app_version,environment,context,evidence
      ) values(
        v_number,p_instance_id,p_support_ticket_id,p_source,p_reporter_user_id,p_reporter_role,
        trim(p_title),trim(p_description),p_category,p_severity,nullif(trim(coalesce(p_correlation_id,'')),''),
        nullif(trim(coalesce(p_route_path,'')),''),nullif(trim(coalesce(p_surface_key,'')),''),
        nullif(trim(coalesce(p_component_key,'')),''),nullif(trim(coalesce(p_app_version,'')),''),
        nullif(trim(coalesce(p_environment,'')),''),coalesce(p_context,'{}'::jsonb),coalesce(p_evidence,'{}'::jsonb)
      ) returning id into v_id;
      exit;
    exception when unique_violation then
      if v_try=5 then raise exception 'INCIDENT_NUMBER_COLLISION'; end if;
    end;
  end loop;
  if v_id is null then raise exception 'INCIDENT_EVIDENCE_MISSING'; end if;
  if not exists(select 1 from public.platform_incident_events where incident_id=v_id and event_type='incident.created') then
    raise exception 'INCIDENT_AUDIT_EVIDENCE_MISSING';
  end if;
  if p_support_ticket_id is not null then
    insert into public.platform_incident_links(incident_id,link_type,reference,metadata)
    values(v_id,'support_ticket',p_support_ticket_id::text,'{}'::jsonb)
    on conflict do nothing;
  end if;
  return jsonb_build_object('id',v_id,'incidentNumber',v_number,'instanceId',p_instance_id,'supportTicketId',p_support_ticket_id);
end;
$$;
revoke all on function public.create_platform_incident_v1(uuid,uuid,text,uuid,text,text,text,text,text,text,text,text,text,text,text,jsonb,jsonb) from public,anon,authenticated;
grant execute on function public.create_platform_incident_v1(uuid,uuid,text,uuid,text,text,text,text,text,text,text,text,text,text,text,jsonb,jsonb) to service_role;

create or replace function public.triage_platform_incident_v1(
  p_incident_id uuid,
  p_ownership text,
  p_reason_code text,
  p_status text,
  p_severity text,
  p_known_failure_id text,
  p_triage_confidence text,
  p_atlas_context jsonb,
  p_actor_user_id uuid
) returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_row public.platform_incidents;
begin
  if p_ownership not in('merchant','platform','shared','undetermined') then raise exception 'INCIDENT_OWNERSHIP_INVALID'; end if;
  if p_status not in('triaged','merchant_action','platform_investigation','auto_healing','repair_proposed','resolved','rejected') then raise exception 'INCIDENT_TRIAGE_STATUS_INVALID'; end if;
  if p_severity not in('low','normal','high','critical') then raise exception 'INCIDENT_SEVERITY_INVALID'; end if;
  if p_triage_confidence not in('low','medium','high','deterministic') then raise exception 'INCIDENT_TRIAGE_CONFIDENCE_INVALID'; end if;
  perform set_config('app.incident_actor_kind','platform',true);
  perform set_config('app.incident_actor_user_id',coalesce(p_actor_user_id::text,''),true);
  update public.platform_incidents
  set ownership=p_ownership,
      ownership_reason_code=nullif(trim(coalesce(p_reason_code,'')),''),
      status=p_status,
      severity=p_severity,
      known_failure_id=nullif(trim(coalesce(p_known_failure_id,'')),''),
      triage_confidence=p_triage_confidence,
      atlas_context=private.incident_redact_json_v1(coalesce(p_atlas_context,'{}'::jsonb)),
      triaged_at=coalesce(triaged_at,now()),
      resolved_at=case when p_status='resolved' then coalesce(resolved_at,now()) else resolved_at end,
      updated_at=now()
  where id=p_incident_id
  returning * into v_row;
  if v_row.id is null then raise exception 'INCIDENT_NOT_FOUND'; end if;
  return jsonb_build_object('id',v_row.id,'incidentNumber',v_row.incident_number,'status',v_row.status,'ownership',v_row.ownership,'severity',v_row.severity);
end;
$$;
revoke all on function public.triage_platform_incident_v1(uuid,text,text,text,text,text,text,jsonb,uuid) from public,anon,authenticated;
grant execute on function public.triage_platform_incident_v1(uuid,text,text,text,text,text,text,jsonb,uuid) to service_role;

create or replace function public.create_incident_repair_request_v1(
