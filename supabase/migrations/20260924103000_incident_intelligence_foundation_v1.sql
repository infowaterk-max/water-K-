-- Shoperation Incident Intelligence v1
-- Canonical engineering incident ledger layered on the existing Support authority.
-- Customer reports remain Support tickets; technical triage/audit/self-healing evidence lives here.

create schema if not exists private;

create or replace function private.incident_redact_json_v1(p_value jsonb)
returns jsonb
language plpgsql
immutable
security definer
set search_path=''
as $$
declare
  v_type text;
  v_result jsonb;
begin
  if p_value is null then return '{}'::jsonb; end if;
  v_type:=jsonb_typeof(p_value);
  if v_type='object' then
    select coalesce(jsonb_object_agg(e.key,
      case
        when lower(e.key)=any(array[
          'email','phone','password','token','authorization','cookie','address',
          'name','full_name','ip','ip_address','access_token','refresh_token'
        ]) then to_jsonb('[redacted]'::text)
        else private.incident_redact_json_v1(e.value)
      end
    ),'{}'::jsonb)
    into v_result
    from jsonb_each(p_value) e;
    return coalesce(v_result,'{}'::jsonb);
  elsif v_type='array' then
    select coalesce(jsonb_agg(private.incident_redact_json_v1(e.value)),'[]'::jsonb)
    into v_result
    from jsonb_array_elements(p_value) e;
    return coalesce(v_result,'[]'::jsonb);
  end if;
  return p_value;
end;
$$;
revoke all on function private.incident_redact_json_v1(jsonb) from public,anon,authenticated;

create table if not exists public.platform_incidents(
  id uuid primary key default gen_random_uuid(),
  incident_number text not null unique,
  instance_id uuid references public.webshop_instances(id) on delete set null,
  support_ticket_id uuid references public.support_tickets(id) on delete set null,
  source text not null check(source in('customer','merchant','system','observability')),
  reporter_user_id uuid references auth.users(id) on delete set null,
  reporter_role text not null check(reporter_role in('anonymous','customer','merchant_owner','merchant_admin','merchant_staff','platform','system','ai')),
  title text not null check(char_length(title) between 3 and 180),
  description text not null check(char_length(description) between 10 and 8000),
  category text not null check(category in('ui','content','catalog','commerce','payment','shipping','account','integration','performance','security','data','other')),
  severity text not null default 'normal' check(severity in('low','normal','high','critical')),
  status text not null default 'submitted' check(status in('submitted','triaged','merchant_action','platform_investigation','auto_healing','repair_proposed','resolved','closed','rejected')),
  ownership text not null default 'undetermined' check(ownership in('undetermined','merchant','platform','shared')),
  ownership_reason_code text,
  triage_confidence text check(triage_confidence is null or triage_confidence in('low','medium','high','deterministic')),
  known_failure_id text,
  correlation_id text,
  route_path text check(route_path is null or (char_length(route_path)<=500 and route_path like '/%' and position('?' in route_path)=0 and position('#' in route_path)=0)),
  surface_key text check(surface_key is null or char_length(surface_key)<=200),
  component_key text check(component_key is null or char_length(component_key)<=200),
  app_version text check(app_version is null or char_length(app_version)<=100),
  environment text check(environment is null or char_length(environment)<=40),
  context jsonb not null default '{}'::jsonb,
  evidence jsonb not null default '{}'::jsonb,
  atlas_context jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  triaged_at timestamptz,
  resolved_at timestamptz,
  closed_at timestamptz
);

create index if not exists platform_incidents_queue_idx on public.platform_incidents(status,severity,created_at);
create index if not exists platform_incidents_instance_idx on public.platform_incidents(instance_id,created_at desc);
create index if not exists platform_incidents_support_idx on public.platform_incidents(support_ticket_id) where support_ticket_id is not null;
create index if not exists platform_incidents_correlation_idx on public.platform_incidents(correlation_id) where correlation_id is not null;
create index if not exists platform_incidents_owner_idx on public.platform_incidents(ownership,status,created_at desc);

create table if not exists public.platform_incident_events(
  id bigint generated by default as identity primary key,
  incident_id uuid not null references public.platform_incidents(id) on delete restrict,
  event_type text not null check(char_length(event_type) between 3 and 100),
  actor_kind text not null check(actor_kind in('anonymous','customer','merchant','platform','system','ai')),
  actor_user_id uuid references auth.users(id) on delete set null,
  correlation_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists platform_incident_events_incident_idx on public.platform_incident_events(incident_id,created_at,id);

create table if not exists public.platform_incident_links(
  id uuid primary key default gen_random_uuid(),
  incident_id uuid not null references public.platform_incidents(id) on delete restrict,
  link_type text not null check(link_type in('support_ticket','observability','known_failure','atlas','github_issue','pull_request','deployment','runbook','other')),
  reference text not null check(char_length(reference) between 1 and 1000),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(incident_id,link_type,reference)
);

create table if not exists public.platform_repair_requests(
  id uuid primary key default gen_random_uuid(),
  incident_id uuid not null references public.platform_incidents(id) on delete restrict,
  repair_kind text not null check(repair_kind in('merchant_action','configuration','data','runbook','code_pr')),
  target_authority text not null check(char_length(target_authority) between 1 and 300),
  risk text not null check(risk in('low','medium','high')),
  status text not null default 'proposed' check(status in('proposed','approved','queued','executing','verified','failed','rejected','rolled_back')),
  auto_apply boolean not null default false,
  proposal jsonb not null default '{}'::jsonb,
  result_evidence jsonb not null default '{}'::jsonb,
  branch_name text,
  pull_request_url text,
  created_by_kind text not null check(created_by_kind in('merchant','platform','system','ai')),
  created_by_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint platform_repair_code_pr_no_direct_auto check(not(repair_kind='code_pr' and auto_apply))
