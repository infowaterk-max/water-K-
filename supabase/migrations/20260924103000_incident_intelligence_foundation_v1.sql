create index if not exists platform_repair_requests_incident_idx on public.platform_repair_requests(incident_id,created_at desc);

create table if not exists public.platform_self_healing_runs(
  id uuid primary key default gen_random_uuid(),
  incident_id uuid not null references public.platform_incidents(id) on delete restrict,
  repair_request_id uuid references public.platform_repair_requests(id) on delete set null,
  runbook_key text not null check(char_length(runbook_key) between 1 and 200),
  mode text not null check(mode in('observe','propose','auto')),
  risk text not null check(risk in('low','medium','high')),
  auto_allowed boolean not null default false,
  status text not null default 'queued' check(status in('queued','running','succeeded','failed','requires_review','rolled_back')),
  input_evidence jsonb not null default '{}'::jsonb,
  output_evidence jsonb not null default '{}'::jsonb,
  rollback_evidence jsonb not null default '{}'::jsonb,
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz not null default now(),
  constraint platform_self_healing_auto_guard check(mode<>'auto' or (risk='low' and auto_allowed))
);
create index if not exists platform_self_healing_runs_incident_idx on public.platform_self_healing_runs(incident_id,created_at desc);

create or replace function private.platform_incident_actor_kind_v1(p_reporter_role text)
returns text language sql immutable set search_path='' as $$
  select case
    when p_reporter_role='anonymous' then 'anonymous'
    when p_reporter_role='customer' then 'customer'
    when p_reporter_role in('merchant_owner','merchant_admin','merchant_staff') then 'merchant'
    when p_reporter_role='platform' then 'platform'
    when p_reporter_role='ai' then 'ai'
    else 'system'
  end;
$$;
