-- V18: post-release verification foundation.
create table if not exists public.post_release_policies(
 id uuid primary key default gen_random_uuid(), policy_key text not null, version integer not null check(version>0), name text not null,
 observation_minutes integer not null default 120 check(observation_minutes between 15 and 10080),
 critical_findings_block boolean not null default true, high_findings_block boolean not null default true,
 min_trusted_checks integer not null default 2 check(min_trusted_checks between 1 and 20), enabled boolean not null default true,
 definition jsonb not null default '{}'::jsonb, created_at timestamptz not null default now(), unique(policy_key,version)
);
alter table public.post_release_policies enable row level security;revoke all on public.post_release_policies from public,anon,authenticated;grant select,insert on public.post_release_policies to service_role;

create table if not exists public.post_release_sessions(
 id uuid primary key default gen_random_uuid(), session_key text not null unique,
 release_candidate_id uuid not null references public.release_candidates(id) on delete restrict,
 policy_id uuid not null references public.post_release_policies(id) on delete restrict,
 source_sha text not null, status text not null default 'observing' check(status in('observing','degraded','rollback_recommended','stable','closed','cancelled')),
 started_at timestamptz not null default now(), observation_ends_at timestamptz not null,
 stable_at timestamptz, closed_at timestamptz, created_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(release_candidate_id,source_sha)
);
alter table public.post_release_sessions enable row level security;revoke all on public.post_release_sessions from public,anon,authenticated;grant select,insert on public.post_release_sessions to service_role;

create table if not exists public.post_release_evidence(
 id uuid primary key default gen_random_uuid(), evidence_key text not null unique, session_id uuid not null references public.post_release_sessions(id) on delete restrict,
 check_kind text not null check(check_kind in('smoke','health','business','integration','manual')),
 status text not null check(status in('pass','fail','error')), trusted boolean not null default false,
 source text not null, observed_at timestamptz not null, evidence jsonb not null default '{}'::jsonb,
 evidence_hash text not null, captured_at timestamptz not null default now()
);
alter table public.post_release_evidence enable row level security;revoke all on public.post_release_evidence from public,anon,authenticated;grant select,insert on public.post_release_evidence to service_role;

create table if not exists public.post_release_findings(
 id uuid primary key default gen_random_uuid(), finding_key text not null unique, session_id uuid not null references public.post_release_sessions(id) on delete restrict,
 severity text not null check(severity in('info','warning','high','critical')), status text not null default 'open' check(status in('open','acknowledged','resolved')),
 title text not null, description text not null, first_detected_at timestamptz not null default now(), last_detected_at timestamptz not null default now(),
 occurrence_count integer not null default 1 check(occurrence_count>0), last_evidence_id uuid references public.post_release_evidence(id) on delete set null,
 acknowledged_by uuid references auth.users(id) on delete set null, resolved_by uuid references auth.users(id) on delete set null, updated_at timestamptz not null default now()
);
alter table public.post_release_findings enable row level security;revoke all on public.post_release_findings from public,anon,authenticated;grant select,insert on public.post_release_findings to service_role;

create table if not exists public.post_release_events(
 id bigint generated by default as identity primary key,event_key text not null unique,session_id uuid not null references public.post_release_sessions(id) on delete restrict,
 event_type text not null check(event_type in('started','evidence_recorded','finding_opened','finding_resolved','degraded','rollback_recommended','stable','closed','cancelled')),
 actor_id uuid references auth.users(id) on delete set null,metadata jsonb not null default '{}'::jsonb,occurred_at timestamptz not null default now()
);
alter table public.post_release_events enable row level security;revoke all on public.post_release_events from public,anon,authenticated;grant select,insert on public.post_release_events to service_role;

