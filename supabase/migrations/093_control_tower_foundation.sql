-- V13: unified business control tower state, human decision tasks and immutable event ledger.

create table if not exists public.control_alerts(
  id uuid primary key default gen_random_uuid(),
  alert_key text not null unique,
  category text not null check(category in ('operations','inventory','service','commercial','customer','system')),
  alert_type text not null,
  severity text not null check(severity in ('info','warning','high','critical')),
  priority_score integer not null default 0 check(priority_score between 0 and 100),
  status text not null default 'open' check(status in ('open','acknowledged','snoozed','resolved','dismissed')),
  title text not null,
  description text not null,
  recommended_action text,
  order_id uuid references public.orders(id) on delete set null,
  customer_id uuid references auth.users(id) on delete set null,
  reseller_id uuid references auth.users(id) on delete set null,
  variant_id uuid references public.product_variants(id) on delete set null,
  opportunity_id uuid references public.commercial_opportunities(id) on delete set null,
  evidence jsonb not null default '{}'::jsonb,
  occurrence_count integer not null default 1 check(occurrence_count>0),
  detected_at timestamptz not null default now(),
  last_detected_at timestamptz not null default now(),
  acknowledged_at timestamptz,
  acknowledged_by uuid references auth.users(id) on delete set null,
  snoozed_until timestamptz,
  resolved_at timestamptz,
  resolved_by uuid references auth.users(id) on delete set null,
  dismissed_at timestamptz,
  dismissed_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create index if not exists control_alerts_queue_idx on public.control_alerts(status,severity,priority_score desc,last_detected_at desc);
create index if not exists control_alerts_order_idx on public.control_alerts(order_id,status);
create index if not exists control_alerts_customer_idx on public.control_alerts(customer_id,status);
create index if not exists control_alerts_variant_idx on public.control_alerts(variant_id,status);
create index if not exists control_alerts_opportunity_idx on public.control_alerts(opportunity_id,status);

alter table public.control_alerts enable row level security;
revoke all on public.control_alerts from public,anon,authenticated;
grant select,insert,update on public.control_alerts to service_role;

create table if not exists public.control_alert_events(
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  alert_id uuid not null references public.control_alerts(id) on delete restrict,
  event_type text not null check(event_type in ('detected','redetected','acknowledged','snoozed','reopened','resolved','dismissed','task_created','task_completed')),
  from_status text,
  to_status text,
  actor_id uuid references auth.users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);
create index if not exists control_alert_events_alert_idx on public.control_alert_events(alert_id,occurred_at desc);
alter table public.control_alert_events enable row level security;
revoke all on public.control_alert_events from public,anon,authenticated;
grant select,insert on public.control_alert_events to service_role;

create table if not exists public.control_tasks(
  id uuid primary key default gen_random_uuid(),
  task_key text not null unique,
  alert_id uuid not null references public.control_alerts(id) on delete restrict,
  status text not null default 'open' check(status in ('open','in_progress','completed','cancelled')),
  priority_score integer not null default 0 check(priority_score between 0 and 100),
  title text not null,
  recommended_action text,
  owner_user_id uuid references auth.users(id) on delete set null,
  due_at timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  completed_by uuid references auth.users(id) on delete set null,
  outcome text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists control_tasks_queue_idx on public.control_tasks(status,priority_score desc,due_at asc);
create index if not exists control_tasks_alert_idx on public.control_tasks(alert_id,status);
alter table public.control_tasks enable row level security;
revoke all on public.control_tasks from public,anon,authenticated;
grant select,insert,update on public.control_tasks to service_role;

create table if not exists public.control_processing_runs(
  id uuid primary key default gen_random_uuid(),
  run_key text not null unique,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  detector_result jsonb not null default '{}'::jsonb,
  task_result jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb
);
alter table public.control_processing_runs enable row level security;
revoke all on public.control_processing_runs from public,anon,authenticated;
grant select,insert,update on public.control_processing_runs to service_role;

comment on table public.control_alerts is 'V13 persistent cross-domain management alerts. Alerts recommend action but do not autonomously mutate commerce/customer state.';
comment on table public.control_tasks is 'Human-in-the-loop decision tasks linked to V13 control alerts.';
comment on table public.control_alert_events is 'Append-only audit events for V13 control alert/task lifecycle.';
