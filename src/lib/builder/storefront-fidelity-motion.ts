import type {StorefrontViewport} from '@/lib/builder/storefront-foundation';
import type {StorefrontVisualStyleSlot} from '@/lib/builder/storefront-visual-style';

export const STOREFRONT_FIDELITY_MOTION_VERSION='shoporation.visual-builder-fidelity-motion.v1' as const;

export const STOREFRONT_MOTION_PRESETS=['none','fade','rise','slide-left','slide-right','scale-in'] as const;
export type StorefrontMotionPreset=typeof STOREFRONT_MOTION_PRESETS[number];
export type StorefrontMotionEasing='standard'|'decelerate'|'accelerate'|'linear';
export type StorefrontMotionTrigger='load'|'reveal'|'hover';

export type StorefrontMotionValue={
  preset?:StorefrontMotionPreset;
  durationMs?:number;
  delayMs?:number;
  distancePx?:number;
  scaleFrom?:number;
  easing?:StorefrontMotionEasing;
  trigger?:StorefrontMotionTrigger;
  once?:boolean;
};

export type StorefrontResponsiveMotion={
  base?:StorefrontMotionValue;
  desktop?:StorefrontMotionValue;
  tablet?:StorefrontMotionValue;
  mobile?:StorefrontMotionValue;
};

export type StorefrontResolvedMotion={
  preset:StorefrontMotionPreset;
  durationMs:number;
  delayMs:number;
  distancePx:number;
  scaleFrom:number;
  easing:StorefrontMotionEasing;
  trigger:StorefrontMotionTrigger;
  once:boolean;
  reducedMotion:boolean;
};

const clamp=(value:number,min:number,max:number)=>Math.min(max,Math.max(min,value));
const finite=(value:unknown):value is number=>typeof value==='number'&&Number.isFinite(value);
const record=(value:unknown):value is Record<string,unknown>=>Boolean(value)&&typeof value==='object'&&!Array.isArray(value);
const EASING:Record<StorefrontMotionEasing,string>={
  standard:'cubic-bezier(.2,.8,.2,1)',
  decelerate:'cubic-bezier(0,0,.2,1)',
  accelerate:'cubic-bezier(.4,0,1,1)',
  linear:'linear',
};

export function sanitizeStorefrontMotionValue(value:unknown):StorefrontMotionValue{
  if(!record(value))return{};
  const result:StorefrontMotionValue={};
  if(typeof value.preset==='string'&&(STOREFRONT_MOTION_PRESETS as readonly string[]).includes(value.preset))result.preset=value.preset as StorefrontMotionPreset;
  if(finite(value.durationMs))result.durationMs=Math.round(clamp(value.durationMs,0,1200));
  if(finite(value.delayMs))result.delayMs=Math.round(clamp(value.delayMs,0,1000));
  if(finite(value.distancePx))result.distancePx=Math.round(clamp(value.distancePx,0,120));
  if(finite(value.scaleFrom))result.scaleFrom=clamp(value.scaleFrom,.7,1);
  if(value.easing==='standard'||value.easing==='decelerate'||value.easing==='accelerate'||value.easing==='linear')result.easing=value.easing;
  if(value.trigger==='load'||value.trigger==='reveal'||value.trigger==='hover')result.trigger=value.trigger;
  if(typeof value.once==='boolean')result.once=value.once;
  return result;
}

function mergedMotion(value:unknown,viewport:StorefrontViewport):StorefrontMotionValue{
  if(!record(value))return{};
  const responsive=['base','desktop','tablet','mobile'].some(key=>Object.prototype.hasOwnProperty.call(value,key));
  if(!responsive)return sanitizeStorefrontMotionValue(value);
  const base=sanitizeStorefrontMotionValue(value.base);
  const desktop={...base,...sanitizeStorefrontMotionValue(value.desktop)};
  const tablet={...desktop,...sanitizeStorefrontMotionValue(value.tablet)};
  const mobile={...tablet,...sanitizeStorefrontMotionValue(value.mobile)};
  return viewport==='desktop'?desktop:viewport==='tablet'?tablet:mobile;
}

export function resolveStorefrontMotion(value:unknown,viewport:StorefrontViewport,reducedMotion=false):StorefrontResolvedMotion{
  const motion=mergedMotion(value,viewport);
  const preset=reducedMotion?'none':motion.preset??'none';
  return{
    preset,
    durationMs:reducedMotion?0:motion.durationMs??420,
    delayMs:reducedMotion?0:motion.delayMs??0,
    distancePx:motion.distancePx??24,
    scaleFrom:motion.scaleFrom??.96,
    easing:motion.easing??'standard',
    trigger:motion.trigger??'reveal',
    once:motion.once??true,
    reducedMotion,
  };
}

/** Initial/final compositing styles for the bounded motion presets. Runtime
 * orchestration can toggle only opacity/transform; no layout properties or
 * arbitrary keyframes are generated by merchant input. */
export function resolveStorefrontMotionStyles(value:unknown,viewport:StorefrontViewport,reducedMotion=false):{initial:StorefrontVisualStyleSlot;active:StorefrontVisualStyleSlot;transition:StorefrontVisualStyleSlot}{
  const motion=resolveStorefrontMotion(value,viewport,reducedMotion);
  if(motion.preset==='none')return{initial:{},active:{},transition:{}};
  const transition={transition:`opacity ${motion.durationMs}ms ${EASING[motion.easing]} ${motion.delayMs}ms, transform ${motion.durationMs}ms ${EASING[motion.easing]} ${motion.delayMs}ms`,willChange:'opacity, transform'} as StorefrontVisualStyleSlot;
  const active:StorefrontVisualStyleSlot={opacity:1,transform:'none'};
  if(motion.preset==='fade')return{initial:{opacity:0},active,transition};
  if(motion.preset==='rise')return{initial:{opacity:0,transform:`translate3d(0, ${motion.distancePx}px, 0)`},active,transition};
  if(motion.preset==='slide-left')return{initial:{opacity:0,transform:`translate3d(${motion.distancePx}px, 0, 0)`},active,transition};
  if(motion.preset==='slide-right')return{initial:{opacity:0,transform:`translate3d(-${motion.distancePx}px, 0, 0)`},active,transition};
  return{initial:{opacity:0,transform:`scale(${motion.scaleFrom})`},active,transition};
}
